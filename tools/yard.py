"""Courtyard furniture layout → public/context/yard.json.

Finds free paved ground inside the site (away from the blocks, planted beds, trees and lamps) and places:
a sports court, playgrounds, parking rows along the site edge, gazebos, benches with bins along the beds,
hedges and flower patches on the beds, manhole covers. Deterministic (fixed seed); rerun after courtyard.py.

Usage: python3 tools/yard.py
"""
import json
import math
import random
import re
from pathlib import Path

from shapely.geometry import LineString, Point, Polygon, box
from shapely.ops import unary_union
from shapely import affinity

ROOT = Path(__file__).resolve().parent.parent
random.seed(7)
r2 = lambda v: round(v, 2)

ctx = json.loads((ROOT / 'public/context/context.json').read_text())
court = json.loads((ROOT / 'public/context/courtyard.json').read_text())
site = Polygon(list(zip(ctx['site'][0::2], ctx['site'][1::2]))).buffer(0)

blocks = []
for m in re.finditer(r"\{ id: (\d+), x: ([-\d.]+), z: ([-\d.]+), w: ([\d.]+), d: ([\d.]+), rot: ([-\d.]+) \}", (ROOT / 'src/data/blocks.ts').read_text()):
    i, x, z, w, d, rot = int(m[1]), *map(float, m.groups()[1:])
    # three.js rotation.y = rot: local (lx, lz) → world (lx cos + lz sin, −lx sin + lz cos)
    c, s = math.cos(rot), math.sin(rot)
    pts = [(x + lx * c + lz * s, z - lx * s + lz * c) for lx, lz in [(-w / 2, -d / 2), (w / 2, -d / 2), (w / 2, d / 2), (-w / 2, d / 2)]]
    blocks.append((Polygon(pts), rot))
block_u = unary_union([b for b, _ in blocks])
lawns = [Polygon(list(zip(r[0::2], r[1::2]))).buffer(0) for r in court['lawnRings']]
lawn_u = unary_union(lawns)
trees = unary_union([Point(x, z).buffer(1.0) for x, z, *_ in court['trees']] + [Point(x, z).buffer(1.2) for x, z in court['young']])
lamps = unary_union([Point(x, z).buffer(0.8) for x, z in court.get('lamps', [])])

free = site.buffer(-1.5).difference(block_u.buffer(5.5)).difference(lawn_u.buffer(0.6)).difference(trees).difference(lamps)
angles = sorted({round(math.degrees(-rot)) % 180 for _, rot in blocks} | {0, 90})


def rect(cx, cz, w, d, deg):
    return affinity.rotate(box(cx - w / 2, cz - d / 2, cx + w / 2, cz + d / 2), deg, origin=(cx, cz))


def place(w, d, score=lambda r: 0, step=2.0):
    """best free position for a w × d rectangle; returns (cx, cz, deg) and removes it from the free area"""
    global free
    best = None
    minx, minz, maxx, maxz = free.bounds
    x = minx
    while x < maxx:
        z = minz
        while z < maxz:
            if free.contains(Point(x, z)):
                for a in angles:
                    r = rect(x, z, w, d, a)
                    if free.contains(r):
                        sc = score(r)
                        if best is None or sc > best[0]:
                            best = (sc, x, z, a, r)
            z += step
        x += step
    if not best:
        return None
    free = free.difference(best[4].buffer(1.5))
    return [r2(best[1]), r2(best[2]), best[3]]


centre = lambda r: -r.centroid.distance(Point(0, 20))            # towards the middle of the complex
edge = lambda r: -r.centroid.distance(site.exterior)             # towards the site boundary

out = {'note': 'generated by tools/yard.py', 'court': None, 'play': [], 'parking': [], 'gazebo': [], 'bench': [], 'hedge': [], 'flowers': [], 'manhole': [], 'bike': []}
for size in [(15, 26), (13, 22), (11, 19)]:
    p = place(*size, centre)
    if p:
        out['court'] = p + list(size); break
for size in [(11, 15), (10, 12), (8, 11), (8, 9)]:
    if len(out['play']) >= 2: break
    p = place(*size, centre)
    if p: out['play'].append(p + list(size))
# parking rows: 2.6 m bays, 5.2 m deep, as long as fits, along the site edge
for n in [14, 12, 10, 8, 8, 6, 6, 6, 5, 5, 4, 4]:
    if len(out['parking']) >= 9: break
    p = place(n * 2.6, 5.2, edge)
    if p: out['parking'].append(p + [n])
for _ in range(3):
    p = place(4.2, 4.2, centre)
    if p: out['gazebo'].append(p)
for _ in range(4):
    p = place(3.2, 1.0, centre, step=1.5)
    if p: out['bike'].append(p)

# benches along the straight edges of the beds, on the paving, looking away from the bed; a bin beside each
bench_free = site.buffer(-1).difference(block_u.buffer(2.5)).difference(lawn_u).difference(trees).difference(lamps)
used = []
for lw in sorted(lawns, key=lambda l: -l.area):
    line = lw.simplify(0.8).exterior
    t = 3.0
    while t < line.length - 1 and len(out['bench']) < 50:
        a, b = line.interpolate(t - 1), line.interpolate(t + 1)
        L = math.hypot(b.x - a.x, b.y - a.y) or 1
        ux, uz = (b.x - a.x) / L, (b.y - a.y) / L
        mx, mz = (a.x + b.x) / 2, (a.y + b.y) / 2
        for nx, nz in [(-uz, ux), (uz, -ux)]:
            px, pz = mx + nx * 0.9, mz + nz * 0.9
            if not bench_free.contains(rect(px, pz, 2.2, 1.0, 0).buffer(0.2)): continue
            if not bench_free.contains(Point(px + nx * 1.6, pz + nz * 1.6)): continue
            if any(math.hypot(px - x, pz - z) < 8 for x, z in used): continue
            used.append((px, pz))
            out['bench'].append([r2(px), r2(pz), r2(math.atan2(nx, nz))])      # yaw: seat faces (nx, nz)
            break
        t += 5.0

# footpaths across the bigger beds: a gently curved paved strip along the bed (and across the largest ones),
# laid where it hits the fewest trees; trees in the way are listed in 'cut' and left out by the app
def curve(a, b, bend, n=14):
    mx, mz = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
    L = math.hypot(b[0] - a[0], b[1] - a[1]) or 1
    cx, cz = mx - (b[1] - a[1]) / L * bend, mz + (b[0] - a[0]) / L * bend
    return LineString([((1 - t) ** 2 * a[0] + 2 * (1 - t) * t * cx + t * t * b[0], (1 - t) ** 2 * a[1] + 2 * (1 - t) * t * cz + t * t * b[1]) for t in [i / n for i in range(n + 1)]])

tree_pts = [Point(x, z) for x, z, *_ in court['trees']]
path_polys = []
for lw in sorted(lawns, key=lambda l: -l.area):
    if lw.area < 200: continue
    mrr = list(lw.minimum_rotated_rectangle.exterior.coords)
    e1, e2 = (mrr[1][0] - mrr[0][0], mrr[1][1] - mrr[0][1]), (mrr[2][0] - mrr[1][0], mrr[2][1] - mrr[1][1])
    l1, l2 = math.hypot(*e1), math.hypot(*e2)
    (lng, sht), (Ll, Ls) = ((e1, e2), (l1, l2)) if l1 >= l2 else ((e2, e1), (l2, l1))
    cx, cz = lw.minimum_rotated_rectangle.centroid.coords[0]
    ul, us = (lng[0] / Ll, lng[1] / Ll), (sht[0] / Ls, sht[1] / Ls)
    jobs = [(ul, us, Ll, Ls)] + ([(us, ul, Ls, Ll)] if lw.area > 520 and Ls > 14 else [])
    for (u, v, L, S) in jobs:
        best = None
        for off in [-0.3, -0.15, 0, 0.15, 0.3]:
            for bend in [-0.12, 0, 0.12]:
                o = (cx + v[0] * S * off, cz + v[1] * S * off)
                ln = curve((o[0] - u[0] * L * 0.6, o[1] - u[1] * L * 0.6), (o[0] + u[0] * L * 0.6, o[1] + u[1] * L * 0.6), bend * S)
                strip = ln.buffer(0.9, cap_style=2).intersection(lw)
                if strip.is_empty: continue
                g = max(getattr(strip, 'geoms', [strip]), key=lambda q: q.area)
                if g.area < 12 or any(g.buffer(1.2).intersects(q) for q in path_polys if q.intersects(lw) and False): continue
                hits = sum(1 for t in tree_pts if g.buffer(1.1).contains(t))
                sc = g.area - hits * 14
                if best is None or sc > best[0]: best = (sc, g)
        if best: path_polys.append(best[1].simplify(0.05))
path_u = unary_union(path_polys) if path_polys else Polygon()
out['paths'] = [[r2(v) for pt in list(g.exterior.coords)[:-1] for v in pt] for g in path_polys if g.geom_type == 'Polygon']
out['cut'] = [[x, z] for x, z, *_ in court['trees'] if path_u.buffer(1.0).contains(Point(x, z))]
trees = unary_union([trees, path_u.buffer(0.5)])        # keep hedges and flowers off the paths

# hedges just inside the edge of the bigger beds (every 1.3 m), flower patches in open spots of the beds
for lw in lawns:
    if lw.area < 60: continue
    inner = lw.buffer(-0.7)
    for g in getattr(inner, 'geoms', [inner]):
        if g.is_empty or g.area < 20: continue
        line = g.exterior
        if random.random() < 0.55:
            t = 0.0
            while t < line.length:
                p = line.interpolate(t)
                if not trees.buffer(0.3).contains(p): out['hedge'].append([r2(p.x), r2(p.y), r2(0.45 + random.random() * 0.2)])
                t += 1.25
    for _ in range(int(lw.area / 140) + (1 if random.random() < 0.5 else 0)):
        for _try in range(30):
            minx, minz, maxx, maxz = lw.bounds
            p = Point(random.uniform(minx, maxx), random.uniform(minz, maxz))
            if lw.buffer(-2.2).contains(p) and not trees.buffer(1.6).contains(p):
                out['flowers'].append([r2(p.x), r2(p.y), r2(1.2 + random.random() * 1.1), random.randrange(4)]); break

# manhole covers and drain grates on the paving
man_free = site.buffer(-2).difference(block_u.buffer(1.5)).difference(lawn_u.buffer(0.4))
minx, minz, maxx, maxz = site.bounds
while len(out['manhole']) < 46:
    p = Point(random.uniform(minx, maxx), random.uniform(minz, maxz))
    if man_free.contains(p) and free.buffer(1.4).contains(p): out['manhole'].append([r2(p.x), r2(p.y), random.randrange(2)])

(ROOT / 'public/context/yard.json').write_text(json.dumps(out, separators=(',', ':')))
print({k: (len(v) if isinstance(v, list) else v) for k, v in out.items() if k != 'note'})
print('court', out['court'], 'play', out['play'], 'parking', out['parking'])
